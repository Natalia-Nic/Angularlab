// Лабораторная работа №6 — Работа с сервисами
//
// В этой лабораторной мы:
// 1) Вынесли данные о проектах в отдельный сервис ProjectsService
// 2) Получаем данные из сервиса в компоненте
// 3) Показываем, как использовать зависимость (Dependency Injection)
// 4) Оставили всё остальное как в прошлых лабах — фильтрация, шаблон и т.д.
// ==========================================

// -----------------------------
// Импорт стандартных модулей Angular
// -----------------------------
import { Component, ViewChild, OnInit } from '@angular/core'; 
// Component — позволяет создать Angular-компонент
// ViewChild — позволяет получить доступ к дочерним компонентам из шаблона
// OnInit — интерфейс жизненного цикла, чтобы выполнить код при инициализации

import { CommonModule } from '@angular/common'; 
// CommonModule нужен для базовых директив (ngIf, ngFor)

import { FormsModule } from '@angular/forms'; 
// FormsModule нужен для [(ngModel)] — двусторонней привязки

// -----------------------------
// Импорт нашего нового сервиса
// -----------------------------
import { ProjectsService } from './projects.service';
// Этот сервис теперь хранит все данные о проектах
// Раньше эти данные были прямо в этом компоненте, теперь мы их вынесли отдельно

// -----------------------------
// Импорт дочерних компонентов
// -----------------------------
import { ProjectListComponent } from '../../project-list/project-list'; 
// Компонент, который отображает список проектов (внутри отдельные карточки)

import { ProjectsFilterComponent } from './projects-filter/projects-filter';
// Компонент, который отвечает за фильтрацию проектов по типу (жилой/коммерческий/все)

import { ProjectsDebugComponent } from './projects-debug/projects-debug';
// Компонент, который показывает отладочную информацию (например, количество проектов)

// -----------------------------
// Декоратор @Component
// Он описывает, как этот компонент работает и где его использовать
// -----------------------------
@Component({
  selector: 'app-projects', // имя тега, который используется в HTML для вставки компонента
  standalone: true, // standalone — компонент не требует AppModule, самодостаточный
  imports: [
    // Сюда указываем всё, что нужно этому компоненту для работы в шаблоне
    CommonModule, // базовые директивы Angular
    FormsModule, // двусторонняя привязка [(ngModel)]
    ProjectListComponent, // компонент списка
    ProjectsFilterComponent, // компонент фильтра
    ProjectsDebugComponent // компонент отладки
  ],
  templateUrl: './projects.html', // путь к HTML-шаблону
  styleUrls: ['./projects.scss'] // путь к файлу со стилями
})

// -----------------------------
// Класс компонента — это логика, которая управляет HTML-шаблоном
// -----------------------------
export class Projects implements OnInit {
  // -----------------------------
  // Поля класса — это данные, которые мы используем в шаблоне (HTML)
  // -----------------------------

  title = '🏗 Наши строительные проекты'; 
  // Просто заголовок, который отображается в <h2>{{ title }}</h2>

  selectedType = 'все'; 
  // Текущий выбранный фильтр для проектов
  // Может быть: 'все', 'жилой' или 'коммерческий'

  projects: any[] = []; 
  // Здесь будет храниться список проектов.
  // Обрати внимание — теперь мы не задаем его вручную!
  // Эти данные придут из сервиса (см. ниже ngOnInit)

  // -----------------------------
  // Внедрение зависимости (Dependency Injection)
  // -----------------------------
  // В конструктор мы добавляем объект сервиса ProjectsService.
  // Angular сам создаёт экземпляр сервиса и "вкалывает" его в компонент.
  constructor(private projectsService: ProjectsService) {}

  // -----------------------------
  // ViewChild — позволяет получить ссылку на дочерние компоненты
  // -----------------------------
  @ViewChild('projectList') projectListComponent!: ProjectListComponent;
  // Эта ссылка появляется после отрисовки шаблона.
  // Мы используем её, чтобы обращаться к методам или свойствам списка проектов.

  @ViewChild(ProjectsDebugComponent) debugComponent!: ProjectsDebugComponent;
  // Здесь получаем доступ ко второму дочернему компоненту — отладочному.

  // -----------------------------
  // ngOnInit() — метод жизненного цикла Angular
  // Он вызывается один раз, когда компонент создаётся.
  // В нём удобно получать данные, вызывать сервисы, настраивать переменные.
  // -----------------------------
  ngOnInit() {
    // Здесь мы получаем данные из сервиса.
    // Теперь компонент не хранит их сам — он просто запрашивает у сервиса.
    this.projects = this.projectsService.getProjects();

    // После этого Angular автоматически обновит шаблон,
    // и все проекты появятся на экране.
  }

  // -----------------------------
  // Геттер filteredProjects — фильтрует проекты по выбранному типу
  // Вызывается каждый раз, когда Angular проверяет шаблон.
  // -----------------------------
  get filteredProjects() {
    // Если выбран "все", возвращаем весь массив без фильтрации
    if (this.selectedType === 'все') {
      return this.projects;
    }

    // Если выбран конкретный тип (жилой/коммерческий),
    // возвращаем только те проекты, у которых type совпадает
    return this.projects.filter(p => p.type === this.selectedType);
  }

  // -----------------------------
  // Метод onSelectedTypeChange() вызывается, когда пользователь меняет фильтр.
  // Этот метод передаётся во вложенный компонент ProjectsFilter через событие.
  // -----------------------------
  onSelectedTypeChange(newType: string) {
    // Сохраняем выбранное пользователем значение
    this.selectedType = newType;

    // Angular автоматически обновит шаблон,
    // потому что selectedType используется в геттере filteredProjects.
  }
}
